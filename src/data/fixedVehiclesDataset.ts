/**
 * Excel 65 Hat tanımını tekil araç kayıtlarına (instance) açar.
 * Araç adedi 2 olan hatlarda (örn: 2 Kamyon) 2 ayrı bağımsız araç kaydı oluşturur.
 * Ankara → Samsun (Satır 19) operasyon kararına göre:
 * - 1 Sabit TIR
 * - 1 Sabit Kamyon
 * - 1 Gece Cross Dock Kamyonu (Sabit araç kotasından ayrı)
 * olarak yapılandırılır.
 */
export function expandAllFixedVehicleInstances(
  configs: FixedLineConfig[] = EXCEL_65_FIXED_LINE_CONFIGS,
  capacities: { kamyonet: number; kamyon: number; tir: number } = {
    kamyonet: 3500,
    kamyon: 12500,
    tir: 22500,
  }
): FixedVehicleInstance[] {
  const instances: FixedVehicleInstance[] = [];

  for (const cfg of configs) {
    const isAnkaraSamsun = cfg.rowNo === 19;

    // 1. Kamyonet Araçları
    for (let i = 1; i <= cfg.kamyonetCount; i++) {
      instances.push({
        vehicleId: `FIXED-ROW${String(cfg.rowNo).padStart(2, '0')}-PAN-${i}`,
        lineRowNo: cfg.rowNo,
        originFacilityId: cfg.originId,
        originFacilityName: cfg.originId,
        destinationFacilityId: cfg.destinationId,
        destinationFacilityName: cfg.destinationId,
        routeLabel: cfg.routeLabel,
        viaWaypoints: cfg.viaWaypoints,
        intermediateRouteText: cfg.viaWaypoints.length > 0 ? cfg.viaWaypoints.join(', ') : '-',
        vehicleType: 'PANELVAN',
        vehicleSeqInRoute: i,
        totalVehiclesInRoute: cfg.kamyonetCount,
        capacityDesi: capacities.kamyonet,
        definedLoadingFacilityIds: [...cfg.parsedLoadingFacilityIds],
        isFixedScheduleVehicle: true,
        isNightCrossDock: false,
        departureTime: '22:00',
        rawLoadingText: cfg.rawLoadingText,
        hasSeparatorAnomaly: cfg.hasSeparatorAnomaly,
        notes: `Excel Satır ${cfg.rowNo}: ${cfg.routeLabel} Sabit Kamyonet / Panelvan #${i}`,
      });
    }

    // 2. Kamyon Araçları
    if (isAnkaraSamsun) {
      // Ankara -> Samsun: 1 Sabit Kamyon + 1 Gece Cross Dock Kamyonu
      // Araç 1: Sabit Kamyon
      instances.push({
        vehicleId: `FIXED-ROW19-KAM-1`,
        lineRowNo: 19,
        originFacilityId: 'ANKARA TM',
        originFacilityName: 'ANKARA TM',
        destinationFacilityId: 'SAMSUN TM',
        destinationFacilityName: 'SAMSUN TM',
        routeLabel: 'Ankara → Samsun (1. Sabit Kamyon)',
        viaWaypoints: [],
        intermediateRouteText: '-',
        vehicleType: 'KAMYON',
        vehicleSeqInRoute: 1,
        totalVehiclesInRoute: 1,
        capacityDesi: capacities.kamyon,
        definedLoadingFacilityIds: [...cfg.parsedLoadingFacilityIds],
        isFixedScheduleVehicle: true,
        isNightCrossDock: false,
        departureTime: '22:00',
        rawLoadingText: cfg.rawLoadingText,
        hasSeparatorAnomaly: false,
        notes: 'Ankara → Samsun 1. Sabit Kamyon (12.500 desi).',
      });

      // Araç 2: Gece Cross Dock Kamyonu (Sabit araç sayısına dahil edilmez)
      instances.push({
        vehicleId: `FIXED-ROW19-KAM-GECE-CD`,
        lineRowNo: 19,
        originFacilityId: 'ANKARA TM',
        originFacilityName: 'ANKARA TM',
        destinationFacilityId: 'SAMSUN TM',
        destinationFacilityName: 'SAMSUN TM',
        routeLabel: 'Ankara → Samsun (Gece Cross Dock Kamyonu)',
        viaWaypoints: [],
        intermediateRouteText: '-',
        vehicleType: 'KAMYON',
        vehicleSeqInRoute: 2,
        totalVehiclesInRoute: 1,
        capacityDesi: capacities.kamyon,
        definedLoadingFacilityIds: [...cfg.parsedLoadingFacilityIds],
        isFixedScheduleVehicle: false,
        isNightCrossDock: true,
        departureTime: '03:30',
        rawLoadingText: cfg.rawLoadingText,
        hasSeparatorAnomaly: false,
        notes: 'Ankara → Samsun Gece Cross Dock Kamyonu (Normal sabit araç kotasından ayrı tutulur).',
      });
    } else {
      for (let i = 1; i <= cfg.kamyonCount; i++) {
        instances.push({
          vehicleId: `FIXED-ROW${String(cfg.rowNo).padStart(2, '0')}-KAM-${i}`,
          lineRowNo: cfg.rowNo,
          originFacilityId: cfg.originId,
          originFacilityName: cfg.originId,
          destinationFacilityId: cfg.destinationId,
          destinationFacilityName: cfg.destinationId,
          routeLabel: cfg.routeLabel,
          viaWaypoints: cfg.viaWaypoints,
          intermediateRouteText: cfg.viaWaypoints.length > 0 ? cfg.viaWaypoints.join(', ') : '-',
          vehicleType: 'KAMYON',
          vehicleSeqInRoute: i,
          totalVehiclesInRoute: cfg.kamyonCount,
          capacityDesi: capacities.kamyon,
          definedLoadingFacilityIds: [...cfg.parsedLoadingFacilityIds],
          isFixedScheduleVehicle: true,
          isNightCrossDock: false,
          departureTime: '22:00',
          rawLoadingText: cfg.rawLoadingText,
          hasSeparatorAnomaly: cfg.hasSeparatorAnomaly,
          notes: `Excel Satır ${cfg.rowNo}: ${cfg.routeLabel} Sabit Kamyon #${i}`,
        });
      }
    }

    // 3. TIR Araçları
    for (let i = 1; i <= cfg.tirCount; i++) {
      instances.push({
        vehicleId: `FIXED-ROW${String(cfg.rowNo).padStart(2, '0')}-TIR-${i}`,
        lineRowNo: cfg.rowNo,
        originFacilityId: cfg.originId,
        originFacilityName: cfg.originId,
        destinationFacilityId: cfg.destinationId,
        destinationFacilityName: cfg.destinationId,
        routeLabel: cfg.routeLabel,
        viaWaypoints: cfg.viaWaypoints,
        intermediateRouteText: cfg.viaWaypoints.length > 0 ? cfg.viaWaypoints.join(', ') : '-',
        vehicleType: 'TIR',
        vehicleSeqInRoute: i,
        totalVehiclesInRoute: cfg.tirCount,
        capacityDesi: capacities.tir,
        definedLoadingFacilityIds: [...cfg.parsedLoadingFacilityIds],
        isFixedScheduleVehicle: true,
        isNightCrossDock: false,
        departureTime: '22:00',
        rawLoadingText: cfg.rawLoadingText,
        hasSeparatorAnomaly: cfg.hasSeparatorAnomaly,
        notes: isAnkaraSamsun
          ? 'Ankara → Samsun 1. Sabit TIR (22.500 desi).'
          : `Excel Satır ${cfg.rowNo}: ${cfg.routeLabel} Sabit TIR #${i}`,
      });
    }
  }

  return instances;
}

export const FixedVehiclesDataset = {
  EXCEL_65_FIXED_LINE_CONFIGS,
  expandAllFixedVehicleInstances,
};
